def test_retrieval_evaluation_pipeline(
    config_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Run the evaluation pipeline and resume from its checkpoint."""

    # 1. Load the experiment configuration and resolve data paths
    root = config_path.parent

    config = load_config(
        config_path,
        project_root=root,
    )

    # 2. Read the chunks and benchmark from the configured files
    chunks = json.loads(config.data.chunks.read_text(encoding="utf-8"))
    benchmark = json.loads(config.data.benchmark.read_text(encoding="utf-8"))

    # 3. Convert chunks into LangChain documents
    documents = [
        Document(
            page_content=chunk["text"],
            metadata={"source": chunk["source"]},
        )
        for chunk in chunks
    ]

    # 4. Prepare the expected query and supporting facts
    sample = benchmark[0]
    expected_fact = sample["supporting_facts"][0]

    # 5. Build the retrieval index from the configured documents
    build_index(config.retriever, documents)

    # 6. Run the complete evaluation pipeline
    summary = run_evaluation(
        config_path=config_path,
        project_root=root,
    )

    # 7. Verify the experiment summary and calculated metrics
    assert summary.status == "completed"
    assert summary.queries_total == 1
    assert summary.queries_evaluated == 1
    assert summary.queries_failed == 0

    assert summary.metrics == {
        "recall@1": 1.0,
        "mrr": 1.0,
    }

    # 8. Load the checkpoint generated by the experiment
    report_path = (
        root / "artifacts" / "experiments" / f"{config_path.stem}_evaluation.json"
    )

    assert report_path.exists()

    report = json.loads(report_path.read_text(encoding="utf-8"))

    assert report["status"] == "completed"
    assert report["queries_total"] == 1
    assert len(report["results"]) == 1

    # 9. Verify retrieval results saved in the checkpoint
    saved = report["results"][0]
    retrieved = saved["retrieved_chunks"]

    assert saved["query_index"] == 0
    assert saved["status"] == "success"
    assert saved["sample"]["query"] == sample["query"]
    assert saved["sample"]["supporting_facts"][0] == expected_fact

    assert len(retrieved) == 1
    assert retrieved[0]["text"] == chunks[0]["text"]
    assert retrieved[0]["source"] == chunks[0]["source"]

    # 10. Verify relevance matches and evaluation metrics
    assert saved["relevance"]["matches"] == [[0, 0]]
    assert saved["relevance"]["gold_count"] == 1
    assert saved["metrics"] == summary.metrics

    # 11. Prevent re-evaluation of already completed queries
    def fail_if_evaluated(
        self: SampleEvaluationService,
        sample: EvaluationSample,
    ) -> NoReturn:
        raise AssertionError("Completed query was evaluated again")

    monkeypatch.setattr(
        SampleEvaluationService,
        "evaluate_sample",
        fail_if_evaluated,
    )

    # 12. Resume the experiment from the existing checkpoint
    resumed_summary = run_evaluation(
        config_path=config_path,
        project_root=root,
    )

    assert resumed_summary == summary

    resumed_report = json.loads(report_path.read_text(encoding="utf-8"))

    assert resumed_report["results"] == report["results"]
